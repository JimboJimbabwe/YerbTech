#!/usr/bin/env python3
"""
WSTG-CONF-06 — HTTP Methods: Tester
Step 2 of 3

Reads the URL list and methods wordlist generated by methods_gen.py,
sends each method against each URL using curl, and records the full
response headers + status code in a structured markdown report.

SAFETY CONSTRAINT: This script will REFUSE to run PUT, DELETE, or PATCH.
Those methods are write operations that can modify or destroy server data
and MUST always be tested manually with explicit intent.

Usage:
  python3 methods_test.py \
    --url-list  inputs/wordlists/curl_urls.txt \
    --methods   inputs/wordlists/methods.txt \
    -o outputs/test_outputs/WSTG-CONF-06/methods_outcome.md

Flags:
  --url-list    curl target URL list (from methods_gen.py)
  --methods     methods wordlist (from methods_gen.py)
  -o / --output output markdown file
  --timeout     per-request timeout in seconds (default: 10)
  --concurrency max parallel curl processes (default: 5)
  --auth-only   only test URLs containing auth path keywords
"""

import argparse
import subprocess
import sys
import os
import re
import json
from datetime import datetime, timezone
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
from urllib.parse import urlparse


# ---------------------------------------------------------------------------
# Safety gate — these methods are NEVER run automatically
# ---------------------------------------------------------------------------
FORBIDDEN_METHODS = {"PUT", "DELETE", "PATCH", "POST"}

AUTH_PATH_KEYWORDS = [
    "login", "logout", "signin", "signout", "sign-in", "sign-out",
    "auth", "authenticate", "authentication",
    "oauth", "oauth2", "oidc",
    "sso", "saml",
    "token", "refresh", "revoke",
    "password", "reset-password", "forgot-password",
    "register", "signup", "sign-up",
    "account", "profile",
    "session", "sessions",
    "mfa", "2fa", "totp",
]

_AUTH_RE = re.compile(
    '|'.join(re.escape(kw) for kw in AUTH_PATH_KEYWORDS),
    re.IGNORECASE,
)


def is_auth_url(url: str) -> bool:
    return bool(_AUTH_RE.search(urlparse(url).path))


# ---------------------------------------------------------------------------
# curl execution
# ---------------------------------------------------------------------------

def run_curl(method: str, url: str, timeout: int) -> dict:
    """
    Run:  curl -s -o /dev/null -D- -X <METHOD> --max-time <timeout> <url>
    Returns a dict with url, method, status_code, headers, allow_header, error.

    CONNECT is handled specially — it's a proxy tunnel request, so we send it
    to the host:port without a path and capture what the server returns.
    """
    result = {
        "url": url,
        "method": method,
        "status_code": None,
        "status_line": "",
        "headers": {},
        "allow_header": "",
        "raw_headers": "",
        "error": None,
    }

    try:
        if method == "CONNECT":
            # CONNECT target is host:port, not a full URL path
            parsed = urlparse(url)
            host = parsed.hostname or parsed.netloc
            port = parsed.port or (443 if parsed.scheme == "https" else 80)
            connect_target = f"{host}:{port}"
            cmd = [
                "curl", "-s", "-v", "--max-time", str(timeout),
                "-X", "CONNECT",
                f"{parsed.scheme}://{connect_target}",
            ]
        else:
            cmd = [
                "curl", "-s",
                "-o", "/dev/null",
                "-D", "-",                   # dump headers to stdout
                "-X", method,
                "--max-time", str(timeout),
                "-A", "Mozilla/5.0",         # basic UA to avoid bot blocks
                url,
            ]

        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout + 5,
        )

        raw = proc.stdout + proc.stderr
        result["raw_headers"] = raw.strip()

        # Parse status line and headers
        lines = raw.replace('\r\n', '\n').split('\n')
        for i, line in enumerate(lines):
            line = line.strip()
            if not line:
                continue
            if line.startswith("HTTP/"):
                result["status_line"] = line
                parts = line.split(' ', 2)
                if len(parts) >= 2:
                    try:
                        result["status_code"] = int(parts[1])
                    except ValueError:
                        pass
            elif ':' in line:
                name, _, value = line.partition(':')
                name = name.strip()
                value = value.strip()
                result["headers"][name.lower()] = value
                if name.lower() == "allow":
                    result["allow_header"] = value

    except subprocess.TimeoutExpired:
        result["error"] = f"Timeout after {timeout}s"
    except FileNotFoundError:
        result["error"] = "curl not found on PATH"
    except Exception as e:
        result["error"] = str(e)

    return result


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args():
    p = argparse.ArgumentParser(
        description='CONF-06 Step 2: Test safe HTTP methods against discovered URLs'
    )
    p.add_argument(
        '--url-list', '-u',
        default='inputs/wordlists/curl_urls.txt',
        help='URL list from methods_gen.py (default: inputs/wordlists/curl_urls.txt)'
    )
    p.add_argument(
        '--methods', '-m',
        default='inputs/wordlists/methods.txt',
        help='Methods wordlist from methods_gen.py (default: inputs/wordlists/methods.txt)'
    )
    p.add_argument(
        '-o', '--output',
        default='outputs/test_outputs/WSTG-CONF-06/methods_outcome.md',
        help='Output markdown file (default: outputs/test_outputs/WSTG-CONF-06/methods_outcome.md)'
    )
    p.add_argument(
        '--timeout', type=int, default=10,
        help='Per-request timeout in seconds (default: 10)'
    )
    p.add_argument(
        '--concurrency', type=int, default=5,
        help='Max parallel curl processes (default: 5)'
    )
    p.add_argument(
        '--auth-only', action='store_true',
        help='Only test URLs matching authentication path patterns'
    )
    return p.parse_args()


# ---------------------------------------------------------------------------
# Load inputs
# ---------------------------------------------------------------------------

def load_lines(path: str, label: str) -> list:
    """Load non-empty, non-comment lines from a file."""
    try:
        with open(path) as f:
            lines = [l.strip() for l in f if l.strip() and not l.strip().startswith('#')]
        return lines
    except FileNotFoundError:
        print(f"[!] {label} file not found: {path}")
        sys.exit(1)


# ---------------------------------------------------------------------------
# Markdown output helpers
# ---------------------------------------------------------------------------

def status_emoji(code):
    if code is None:
        return "⚠"
    if code < 300:
        return "✅"
    if code < 400:
        return "↪"
    if code < 500:
        return "🚫"
    return "⚠"


def write_markdown(output_path: str, results: list, methods: list, meta: dict):
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

    # Group by URL
    from collections import defaultdict
    by_url = defaultdict(list)
    for r in results:
        by_url[r["url"]].append(r)

    lines = []
    lines.append("# CONF-06 HTTP Methods — Test Outcome")
    lines.append("")
    lines.append(f"**Generated:** {meta['generated']}")
    lines.append(f"**URL list:** `{meta['url_list']}`")
    lines.append(f"**Methods tested:** `{', '.join(methods)}`")
    lines.append(f"**Total requests:** {meta['total_requests']}")
    lines.append(f"**Errors:** {meta['errors']}")
    lines.append("")
    lines.append("> ⚠ PUT / DELETE / PATCH were NOT tested automatically.")
    lines.append("> If OPTIONS reveals these methods are allowed, test them **manually**.")
    lines.append("")
    lines.append("---")
    lines.append("")

    for url in sorted(by_url.keys()):
        url_results = by_url[url]
        auth_tag = " 🔐 AUTH PATHWAY" if is_auth_url(url) else ""
        lines.append(f"## `{url}`{auth_tag}")
        lines.append("")
        lines.append("| Method | Status | Allow Header | Notes |")
        lines.append("|--------|--------|--------------|-------|")

        for r in sorted(url_results, key=lambda x: x["method"]):
            method = r["method"]
            code = r["status_code"]
            status = f"{status_emoji(code)} {code}" if code else f"⚠ {r.get('error', 'Error')}"
            allow = r["allow_header"] or "—"
            notes = ""

            if r.get("error"):
                notes = f"Error: {r['error']}"
            else:
                dangerous = []
                for dm in ["PUT", "DELETE", "PATCH"]:
                    if dm in (r["allow_header"] or "").upper():
                        dangerous.append(dm)
                if dangerous:
                    notes = f"⚠ **Dangerous method advertised: {', '.join(dangerous)}** — verify manually"
                elif "CONNECT" in (r["allow_header"] or "").upper():
                    notes = "⚠ CONNECT in Allow — proxy tunnelling may be possible"
                elif method == "TRACE" and code and code < 300:
                    notes = "⚠ TRACE accepted — XST risk"
                elif method == "OPTIONS" and code == 200:
                    notes = "OPTIONS 200 — review Allow header"

            lines.append(f"| `{method}` | {status} | `{allow}` | {notes} |")

        lines.append("")

        # Raw headers block (collapsed)
        for r in sorted(url_results, key=lambda x: x["method"]):
            if r["raw_headers"]:
                lines.append(f"<details>")
                lines.append(f"<summary>Raw headers — {r['method']}</summary>")
                lines.append("")
                lines.append("```")
                lines.append(r["raw_headers"])
                lines.append("```")
                lines.append("")
                lines.append("</details>")
                lines.append("")

        lines.append("---")
        lines.append("")

    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    args = parse_args()

    print("=" * 60)
    print("CONF-06 — HTTP Methods Tester")
    print("=" * 60)

    # Load inputs
    urls = load_lines(args.url_list, "URL list")
    methods_raw = load_lines(args.methods, "Methods wordlist")

    # Safety gate
    methods = []
    blocked = []
    for m in methods_raw:
        m_upper = m.upper().strip()
        if m_upper in FORBIDDEN_METHODS:
            blocked.append(m_upper)
        else:
            methods.append(m_upper)

    if blocked:
        print(f"\n[!] SAFETY: Removed forbidden methods from run: {', '.join(blocked)}")
        print(f"    These methods (PUT/DELETE/PATCH/POST) MUST be tested manually.")

    if not methods:
        print("[!] No safe methods remain after filtering. Exiting.")
        sys.exit(1)

    print(f"[*] URLs loaded:    {len(urls)}")
    print(f"[*] Methods:        {', '.join(methods)}")

    if args.auth_only:
        urls = [u for u in urls if is_auth_url(u)]
        print(f"[*] Auth-only mode: {len(urls)} URLs")

    auth_count = sum(1 for u in urls if is_auth_url(u))
    print(f"[*] Auth pathway URLs: {auth_count}/{len(urls)}")

    total = len(urls) * len(methods)
    print(f"[*] Total requests to send: {total}")
    print(f"[*] Concurrency: {args.concurrency}, Timeout: {args.timeout}s")
    print()

    # Build task list
    tasks = [(method, url) for url in urls for method in methods]
    results = []
    errors = 0

    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        future_map = {
            pool.submit(run_curl, method, url, args.timeout): (method, url)
            for method, url in tasks
        }
        done = 0
        for future in as_completed(future_map):
            result = future.result()
            results.append(result)
            done += 1
            if result.get("error"):
                errors += 1
                print(f"  [{done}/{total}] ⚠ {result['method']:8s} {result['url']} — {result['error']}")
            else:
                code = result["status_code"] or "?"
                allow = f" Allow: {result['allow_header']}" if result["allow_header"] else ""
                print(f"  [{done}/{total}] {result['method']:8s} {code}  {result['url']}{allow}")

    # Write output
    meta = {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "url_list": args.url_list,
        "total_requests": total,
        "errors": errors,
    }
    write_markdown(args.output, results, methods, meta)

    print(f"\n[+] Outcome written → {args.output}")
    print(f"\n{'=' * 60}")
    print("SUMMARY")
    print(f"{'=' * 60}")
    print(f"  URLs tested:       {len(urls)}")
    print(f"  Methods:           {', '.join(methods)}")
    print(f"  Total requests:    {total}")
    print(f"  Errors:            {errors}")
    print(f"  Output:            {args.output}")
    print(f"\n  Next: run methods_outcome.py -i {args.output}")


if __name__ == "__main__":
    main()
